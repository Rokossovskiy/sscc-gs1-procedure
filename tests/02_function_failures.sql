-- 6. Функция вернула NULL
DECLARE @s NVARCHAR(22);
BEGIN TRAN;
EXEC (N'ALTER FUNCTION dbo.fn_GenerateGS1SSCC (@SSCC17 NVARCHAR(17)) RETURNS NVARCHAR(25)
        AS BEGIN RETURN NULL; END');
BEGIN TRY EXEC dbo.sp_GetNextGS1SSCC @SSCC = @s OUTPUT; END TRY
BEGIN CATCH SELECT N'fn NULL' AS test, ERROR_NUMBER() AS err, ERROR_MESSAGE() AS msg; END CATCH;
IF @@TRANCOUNT > 0 ROLLBACK;
GO

-- 7. Функция вернула строку с хвостовым пробелом
DECLARE @s NVARCHAR(22);
BEGIN TRAN;
EXEC (N'ALTER FUNCTION dbo.fn_GenerateGS1SSCC (@SSCC17 NVARCHAR(17)) RETURNS NVARCHAR(25)
        AS BEGIN RETURN N''(00)'' + @SSCC17 + N''6 ''; END');
BEGIN TRY EXEC dbo.sp_GetNextGS1SSCC @SSCC = @s OUTPUT; END TRY
BEGIN CATCH SELECT N'fn trailing space' AS test, ERROR_NUMBER() AS err, ERROR_MESSAGE() AS msg; END CATCH;
IF @@TRANCOUNT > 0 ROLLBACK;
GO

-- 8. Runtime-ошибка внутри функции (деление на ноль)
DECLARE @s NVARCHAR(22);
BEGIN TRAN;
EXEC (N'ALTER FUNCTION dbo.fn_GenerateGS1SSCC (@SSCC17 NVARCHAR(17)) RETURNS NVARCHAR(25)
        AS BEGIN RETURN N''(00)'' + @SSCC17 + CAST(1 / (LEN(@SSCC17) - 17) AS NVARCHAR(1)); END');
BEGIN TRY EXEC dbo.sp_GetNextGS1SSCC @SSCC = @s OUTPUT; END TRY
BEGIN CATCH SELECT N'fn runtime error' AS test, ERROR_NUMBER() AS err, ERROR_MESSAGE() AS msg; END CATCH;
IF @@TRANCOUNT > 0 ROLLBACK;
GO

-- 9. Функция вернула нецифровой символ вместо контрольной цифры (NCHAR(178), надстрочная двойка)
